"""Screening analysis and diagnostic telemetry engine for Youloss.

Parses PGNs and match metadata generated by tournament harnesses,
computes comparative telemetry (depth, time allocation across game phases,
and score-change proxy drops), partitions runs by immutable binary and runner
configuration, and reports failed or incomplete runs separately.
"""

from __future__ import annotations

import argparse
import json
import math
import re
import sys
from dataclasses import asdict, dataclass, field
from datetime import datetime, timezone
from decimal import Decimal
from pathlib import Path
from statistics import NormalDist

import chess
import chess.pgn

# Fastchess comment regex: e.g. +1.09/18 0.617s or -0.50/22 1.250s or +M4/20 0.050s
_COMMENT_RE = re.compile(r"([+-]?(?:M\d+|\d+(?:\.\d+)?))/(\d+)\s+(\d+(?:\.\d+)?)s")
_MIN_PAIRS_FOR_CI = 30
_MAX_COMPARABLE_EVAL_CP = 1000.0


@dataclass
class PhaseStats:
    moves: int = 0
    total_time_s: float = 0.0
    total_depth: int = 0

    @property
    def avg_time_s(self) -> float:
        return self.total_time_s / self.moves if self.moves > 0 else 0.0

    @property
    def avg_depth(self) -> float:
        return self.total_depth / self.moves if self.moves > 0 else 0.0


@dataclass
class EngineTelemetry:
    opening: PhaseStats = field(default_factory=PhaseStats)  # moves 1-10
    early_mid: PhaseStats = field(default_factory=PhaseStats)  # moves 11-20
    late_mid: PhaseStats = field(default_factory=PhaseStats)  # moves 21-40
    endgame: PhaseStats = field(default_factory=PhaseStats)  # moves 41+
    score_drops_100cp: int = 0  # Exploratory, unverified score-change proxy
    score_drops_200cp: int = 0  # Exploratory, unverified score-change proxy
    excluded_eval_outliers: int = 0
    max_move_time_s: float = 0.0


@dataclass(frozen=True)
class RunPartitionKey:
    engine_sha256: str
    sf_engine_sha256: str
    runner_sha256: str
    runner_version: str
    tc: str
    threads: int
    hash_mb: int
    concurrency: int
    move_overhead_ms: int
    book: str
    book_sha256: str
    engine_options: str


@dataclass
class ExcludedRun:
    rundir: str
    reason: str


def parse_eval_cp(eval_str: str) -> float | None:
    """Parse a plausible centipawn score; mate and extreme scores are incomparable."""
    if eval_str.lstrip("+-").startswith("M"):
        return None
    try:
        score_cp = float(eval_str) * 100.0
    except ValueError:
        return None
    if not math.isfinite(score_cp) or abs(score_cp) > _MAX_COMPARABLE_EVAL_CP:
        return None
    return score_cp


def get_game_phase(fullmove_number: int, stats: EngineTelemetry) -> PhaseStats:
    if fullmove_number <= 10:
        return stats.opening
    if fullmove_number <= 20:
        return stats.early_mid
    if fullmove_number <= 40:
        return stats.late_mid
    return stats.endgame


def parse_pgn_game(
    game: chess.pgn.Game,
    tm_stats: EngineTelemetry,
    sf_stats: EngineTelemetry,
    results: dict[str, int],
    game_idx: int,
) -> None:
    """Parse a single PGN game using board state and attribute telemetry to mover."""
    white = game.headers.get("White", "").strip().lower()
    black = game.headers.get("Black", "").strip().lower()
    res = game.headers.get("Result", "").strip()

    valid_engines = {"tm", "sf"}
    if white not in valid_engines or black not in valid_engines or white == black:
        raise ValueError(
            f"Invalid engine labels: White='{white}', Black='{black}' at game {game_idx}"
        )

    if res not in ("1-0", "0-1", "1/2-1/2"):
        raise ValueError(
            f"Unfinished or invalid game result '{res}' at game {game_idx}"
        )

    results["total_games"] += 1
    if res == "1/2-1/2":
        results["draws"] += 1
    elif (res == "1-0" and white == "tm") or (res == "0-1" and black == "tm"):
        results["tm_wins"] += 1
    elif (res == "1-0" and white == "sf") or (res == "0-1" and black == "sf"):
        results["sf_wins"] += 1

    board = game.board()
    prev_eval: dict[str, float] = {}

    for node in game.mainline():
        move = node.move
        side = board.turn
        mover_is_tm = (side == chess.WHITE and white == "tm") or (
            side == chess.BLACK and black == "tm"
        )
        mover_tag = "tm" if mover_is_tm else "sf"
        engine_stat = tm_stats if mover_is_tm else sf_stats
        fullmove = board.fullmove_number

        phase = get_game_phase(fullmove, engine_stat)

        comment = node.comment
        match = _COMMENT_RE.search(comment)
        if match:
            eval_str, depth_str, time_str = match.groups()
            depth = int(depth_str)
            time_s = float(time_str)

            phase.moves += 1
            phase.total_time_s += time_s
            phase.total_depth += depth
            engine_stat.max_move_time_s = max(engine_stat.max_move_time_s, time_s)

            eval_cp = parse_eval_cp(eval_str)
            if eval_cp is None:
                # Mates use another scale; extreme numeric scores are also not
                # useful for this deliberately rough centipawn-change proxy.
                if not eval_str.lstrip("+-").startswith("M"):
                    engine_stat.excluded_eval_outliers += 1
                prev_eval.pop(mover_tag, None)
            else:
                if mover_tag in prev_eval:
                    eval_drop = prev_eval[mover_tag] - eval_cp
                    if eval_drop >= 200.0:
                        engine_stat.score_drops_200cp += 1
                    elif eval_drop >= 100.0:
                        engine_stat.score_drops_100cp += 1
                prev_eval[mover_tag] = eval_cp

        board.push(move)


def parse_pgn_file(
    pgn_path: Path,
) -> tuple[dict[str, int], EngineTelemetry, EngineTelemetry, int]:
    """Parse entire PGN file and return (results, tm_stats, sf_stats, game_count)."""
    tm_stats = EngineTelemetry()
    sf_stats = EngineTelemetry()
    results = {"tm_wins": 0, "sf_wins": 0, "draws": 0, "total_games": 0}
    game_count = 0

    with pgn_path.open("r", encoding="utf-8", errors="replace") as f:
        while True:
            try:
                game = chess.pgn.read_game(f)
            except Exception as e:
                raise ValueError(f"Malformed PGN at game {game_count + 1}: {e}") from e
            if game is None:
                break
            game_count += 1
            parse_pgn_game(game, tm_stats, sf_stats, results, game_count)

    return results, tm_stats, sf_stats, game_count


def parse_paired_scores(pgn_path: Path) -> tuple[list[float], int]:
    """Return paired-opening TM scores and the number of unpaired games.

    Games are paired only within this PGN run, using Round and initial FEN,
    with each engine playing White once. A pair score is the mean of the two
    game scores from TM's perspective.
    """
    games_by_opening: dict[tuple[str, str], list[tuple[str, float]]] = {}
    unpairable_games = 0

    with pgn_path.open("r", encoding="utf-8", errors="replace") as f:
        while True:
            try:
                game = chess.pgn.read_game(f)
            except Exception as e:
                raise ValueError(f"Malformed PGN while pairing games: {e}") from e
            if game is None:
                break

            headers = game.headers
            white = headers.get("White", "").strip().lower()
            black = headers.get("Black", "").strip().lower()
            result = headers.get("Result", "").strip()
            if white not in {"tm", "sf"} or black not in {"tm", "sf"} or white == black:
                unpairable_games += 1
                continue
            if result not in {"1-0", "1/2-1/2", "0-1"}:
                unpairable_games += 1
                continue

            white_score = {"1-0": 1.0, "1/2-1/2": 0.5, "0-1": 0.0}[result]
            tm_score = white_score if white == "tm" else 1.0 - white_score
            round_id = headers.get("Round", "").strip()
            fen = headers.get("FEN", "").strip()
            if not fen and headers.get("SetUp") != "1":
                fen = chess.STARTING_FEN

            if not round_id or not fen:
                unpairable_games += 1
                continue

            games_by_opening.setdefault((round_id, fen), []).append((white, tm_score))

    paired_scores: list[float] = []
    for entries in games_by_opening.values():
        if len(entries) == 2 and {entry[0] for entry in entries} == {"tm", "sf"}:
            paired_scores.append((entries[0][1] + entries[1][1]) / 2.0)
        else:
            unpairable_games += len(entries)

    return paired_scores, unpairable_games


def summarize_paired_scores(
    paired_scores: list[float], unpaired_games: int
) -> dict[str, float | int | str | None]:
    """Summarize paired scores, withholding intervals for small/constant samples."""
    count = len(paired_scores)
    paired_score = sum(paired_scores) / count if count else None
    ci_low: float | None = None
    ci_high: float | None = None
    method = (
        f"Not estimated (requires at least {_MIN_PAIRS_FOR_CI} matched opening pairs)"
    )

    if count >= _MIN_PAIRS_FOR_CI:
        variance = sum((score - paired_score) ** 2 for score in paired_scores) / (
            count - 1
        )
        if variance > 0:
            degrees_of_freedom = count - 1
            margin = (
                _student_t_critical_975(degrees_of_freedom) * (variance / count) ** 0.5
            )
            ci_low = max(0.0, paired_score - margin)
            ci_high = min(1.0, paired_score + margin)
            method = (
                "Approximate 95% paired Student-t CI over paired-opening mean "
                "scores (Cornish-Fisher critical value; df=n-1)"
            )
        else:
            method = "Not estimated (paired-opening scores have zero observed variance)"

    return {
        "paired_openings": count,
        "paired_games": count * 2,
        "unpaired_games": unpaired_games,
        "score": paired_score,
        "ci95_low": ci_low,
        "ci95_high": ci_high,
        "method": method,
    }


def _student_t_critical_975(degrees_of_freedom: int) -> float:
    """Approximate the two-sided 95% Student-t critical value.

    The paired-score interval is only reported for at least 30 pairs (29 df).
    A fourth-order Cornish-Fisher expansion is accurate at that threshold and
    avoids adding SciPy just to calculate the critical value.
    """
    if degrees_of_freedom < 1:
        raise ValueError("degrees_of_freedom must be positive")

    z = NormalDist().inv_cdf(0.975)
    z2 = z * z
    z3 = z2 * z
    z5 = z3 * z2
    z7 = z5 * z2
    z9 = z7 * z2
    df = degrees_of_freedom

    return (
        z
        + (z3 + z) / (4 * df)
        + (5 * z5 + 16 * z3 + 3 * z) / (96 * df**2)
        + (3 * z7 + 19 * z5 + 17 * z3 - 15 * z) / (384 * df**3)
        + (79 * z9 + 776 * z7 + 1482 * z5 - 1920 * z3 - 945 * z) / (92160 * df**4)
    )


def validate_run_directory(
    rundir: Path,
) -> tuple[RunPartitionKey | None, str | None, dict]:
    """Validate rundir, check meta.json reconciliation, return (key, failure_reason, meta)."""
    meta_path = rundir / "meta.json"
    if not meta_path.is_file():
        return None, "Missing meta.json", {}

    try:
        with meta_path.open("r", encoding="utf-8") as f:
            meta = json.load(f)
    except (OSError, json.JSONDecodeError) as e:
        return None, f"Invalid meta.json JSON: {e}", {}

    if not isinstance(meta, dict):
        return None, "meta.json must be a JSON object", {}

    if meta.get("timeout") in (1, True, "1") or "timeout" in str(
        meta.get("exit_fastchess", "")
    ):
        return (
            None,
            f"Run timed out (exit_fastchess: {meta.get('exit_fastchess')})",
            meta,
        )

    for key, name in [
        ("exit_fastchess", "Fastchess"),
        ("exit_checker", "Checker"),
        ("exit_time_profile", "Time profile"),
        ("exit_tee", "Tee output"),
    ]:
        val = str(meta.get(key, "missing"))
        if val != "0":
            return None, f"{name} failed with code {val}", meta

    pgn_path = rundir / "match.pgn"
    if not pgn_path.is_file():
        return None, "Missing match.pgn", meta

    eng_sha = str(meta.get("engine_sha256", "")).strip()
    if not eng_sha or eng_sha.lower() == "unknown":
        return None, "Missing immutable engine SHA (engine_sha256)", meta

    runner_sha = str(meta.get("runner_sha256", "")).strip()
    if not runner_sha or runner_sha.lower() == "unknown":
        return None, "Missing fastchess runner SHA (runner_sha256)", meta

    if "sf_engine_sha256" in meta:
        raw_sf_sha = meta.get("sf_engine_sha256")
        sf_sha = str(raw_sf_sha).strip() if raw_sf_sha is not None else ""
        if not sf_sha or sf_sha.lower() in ("unknown", "none"):
            return (
                None,
                "Missing immutable baseline engine SHA (sf_engine_sha256)",
                meta,
            )
    else:
        sf_sha = eng_sha

    tc = str(meta.get("tc", "")).strip()
    if not tc or tc.lower() == "unknown":
        return None, "Missing time control (tc)", meta

    book = str(meta.get("book", "")).strip()
    book_sha = str(meta.get("book_sha256", "")).strip()
    if (
        not book
        or not book_sha
        or book.lower() == "unknown"
        or book_sha.lower() == "unknown"
    ):
        return None, "Missing opening book identity or book SHA", meta

    numeric_settings: dict[str, int] = {}
    for name in ("threads", "hash_mb", "concurrency", "move_overhead_ms"):
        value = meta.get(name)
        if isinstance(value, bool) or not isinstance(value, int):
            return None, f"Missing or invalid comparison setting ({name})", meta
        if value < 0 or (name != "move_overhead_ms" and value == 0):
            return None, f"Invalid comparison setting ({name}={value})", meta
        numeric_settings[name] = value

    control_match = re.fullmatch(r"([0-9]+(?:\.[0-9]+)?)\+([0-9]+(?:\.[0-9]+)?)", tc)
    if control_match is None:
        return None, f"Unsupported or malformed time control ({tc})", meta

    base_ms = int(Decimal(control_match.group(1)) * 1000)
    increment_ms = int(Decimal(control_match.group(2)) * 1000)
    move_horizon = 50 if base_ms >= 1000 else (base_ms * 5) // 100
    initial_budget_ms = base_ms + increment_ms * (move_horizon - 1)
    if initial_budget_ms <= 0:
        return None, f"Time control has non-positive initial budget ({tc})", meta

    overhead_reserve_ms = numeric_settings["move_overhead_ms"] * (2 + move_horizon)
    if overhead_reserve_ms * 10 > initial_budget_ms:
        return (
            None,
            (
                "Move Overhead exceeds the 10% initial-budget policy "
                f"({overhead_reserve_ms}ms reserved vs {initial_budget_ms}ms available; "
                f"tc={tc}, mtg={move_horizon})"
            ),
            meta,
        )

    engine_options = str(meta.get("engine_options", "")).strip()
    if not engine_options or engine_options.lower() == "unknown":
        return None, "Missing engine options", meta

    completed = meta.get("completed_games")
    if isinstance(completed, bool) or not isinstance(completed, int) or completed < 0:
        return None, "Missing or invalid completed_games count", meta
    expected = meta.get("expected_games")
    is_sprt = bool(meta.get("sprt"))
    if not is_sprt and (
        isinstance(expected, bool) or not isinstance(expected, int) or expected < 0
    ):
        return None, "Missing or invalid expected_games count for fixed run", meta

    runner_ver = str(
        meta.get("runner_tag") or meta.get("runner_commit") or "unknown"
    ).strip()

    partition_key = RunPartitionKey(
        engine_sha256=eng_sha,
        sf_engine_sha256=sf_sha,
        runner_sha256=runner_sha,
        runner_version=runner_ver,
        tc=tc,
        threads=numeric_settings["threads"],
        hash_mb=numeric_settings["hash_mb"],
        concurrency=numeric_settings["concurrency"],
        move_overhead_ms=numeric_settings["move_overhead_ms"],
        book=book,
        book_sha256=book_sha,
        engine_options=engine_options,
    )
    return partition_key, None, meta


def accumulate_telemetry(dst: EngineTelemetry, src: EngineTelemetry) -> None:
    for phase_name in ("opening", "early_mid", "late_mid", "endgame"):
        p_src: PhaseStats = getattr(src, phase_name)
        p_dst: PhaseStats = getattr(dst, phase_name)
        p_dst.moves += p_src.moves
        p_dst.total_time_s += p_src.total_time_s
        p_dst.total_depth += p_src.total_depth

    dst.score_drops_100cp += src.score_drops_100cp
    dst.score_drops_200cp += src.score_drops_200cp
    dst.excluded_eval_outliers += src.excluded_eval_outliers
    dst.max_move_time_s = max(dst.max_move_time_s, src.max_move_time_s)


def generate_recommendations(
    tm: EngineTelemetry, sf: EngineTelemetry, results: dict[str, int]
) -> list[str]:
    recs = []
    depth_diff_open = sf.opening.avg_depth - tm.opening.avg_depth
    if depth_diff_open > 0.8:
        recs.append(
            f"Opening depth deficit: TM avg {tm.opening.avg_depth:.1f} vs SF {sf.opening.avg_depth:.1f} (-{depth_diff_open:.1f})."
        )
    depth_diff_mid = sf.early_mid.avg_depth - tm.early_mid.avg_depth
    if depth_diff_mid > 0.8:
        recs.append(
            f"Middlegame depth deficit: TM avg {tm.early_mid.avg_depth:.1f} vs SF {sf.early_mid.avg_depth:.1f} (-{depth_diff_mid:.1f})."
        )
    if tm.endgame.moves > 20 and tm.endgame.avg_time_s < sf.endgame.avg_time_s * 0.7:
        recs.append(
            f"Endgame time allocation low: TM avg {tm.endgame.avg_time_s:.2f}s vs SF {sf.endgame.avg_time_s:.2f}s."
        )
    if not recs:
        recs.append(
            "Time allocation and search curves within expected screening thresholds."
        )
    return recs


def generate_partition_markdown(
    key: RunPartitionKey,
    results: dict[str, int],
    paired_results: dict,
    tm: EngineTelemetry,
    sf: EngineTelemetry,
    recs: list[str],
    source_runs: list[str],
) -> list[str]:
    tot = results["total_games"]
    w = results["tm_wins"]
    l = results["sf_wins"]
    d = results["draws"]
    pts = w + 0.5 * d
    pct = (pts / tot * 100.0) if tot > 0 else 0.0
    if paired_results["score"] is None:
        paired_score_text = f"Score/interval unavailable: {paired_results['method']}."
    elif paired_results["ci95_low"] is None or paired_results["ci95_high"] is None:
        paired_score_text = (
            f"Score **{paired_results['score'] * 100:.2f}%**; "
            f"interval unavailable: {paired_results['method']}."
        )
    else:
        paired_score_text = (
            f"Score **{paired_results['score'] * 100:.2f}%**; {paired_results['method']}: "
            f"{paired_results['ci95_low'] * 100:.2f}%–{paired_results['ci95_high'] * 100:.2f}%."
        )

    return [
        f"### Partition: TC `{key.tc}`, Youloss SHA `{key.engine_sha256[:12]}`, SF SHA `{key.sf_engine_sha256[:12]}`, Runner SHA `{key.runner_sha256[:12]}`",
        f"- **Configuration**: Threads={key.threads}, Hash={key.hash_mb}MB, Concurrency={key.concurrency}, Overhead={key.move_overhead_ms}ms",
        f"- **Runner Build**: `{key.runner_version}` (SHA `{key.runner_sha256[:12]}`)",
        f"- **Book**: `{key.book}` (SHA `{key.book_sha256[:12]}`)",
        f"- **Engine Options**: `{key.engine_options}`",
        f"- **Games**: {tot} (Score: **{pct:.2f}%** | {w}W - {d}D - {l}L)",
        f"- **Paired-color score**: {paired_results['paired_openings']} opening pairs / {paired_results['paired_games']} games; unpaired games={paired_results['unpaired_games']}.",
        f"  {paired_score_text}",
        f"- **Source Runs ({len(source_runs)})**: "
        + ", ".join(f"`{Path(r).name}`" for r in source_runs),
        "",
        "| Phase (Moves) | Youloss Avg Time | SF Avg Time | Youloss Avg Depth | SF Avg Depth | Depth Delta |",
        "| :--- | :--- | :--- | :--- | :--- | :--- |",
        f"| Opening (1-10) | {tm.opening.avg_time_s:.3f}s | {sf.opening.avg_time_s:.3f}s | {tm.opening.avg_depth:.1f} | {sf.opening.avg_depth:.1f} | {tm.opening.avg_depth - sf.opening.avg_depth:+.1f} |",
        f"| Early Mid (11-20) | {tm.early_mid.avg_time_s:.3f}s | {sf.early_mid.avg_time_s:.3f}s | {tm.early_mid.avg_depth:.1f} | {sf.early_mid.avg_depth:.1f} | {tm.early_mid.avg_depth - sf.early_mid.avg_depth:+.1f} |",
        f"| Late Mid (21-40) | {tm.late_mid.avg_time_s:.3f}s | {sf.late_mid.avg_time_s:.3f}s | {tm.late_mid.avg_depth:.1f} | {sf.late_mid.avg_depth:.1f} | {tm.late_mid.avg_depth - sf.late_mid.avg_depth:+.1f} |",
        f"| Endgame (41+) | {tm.endgame.avg_time_s:.3f}s | {sf.endgame.avg_time_s:.3f}s | {tm.endgame.avg_depth:.1f} | {sf.endgame.avg_depth:.1f} | {tm.endgame.avg_depth - sf.endgame.avg_depth:+.1f} |",
        "",
        f"- **Score-change proxy drops >= 100 cp (unverified by reanalysis)**: Youloss {tm.score_drops_100cp} | SF {sf.score_drops_100cp}",
        f"- **Score-change proxy drops >= 200 cp (unverified by reanalysis)**: Youloss {tm.score_drops_200cp} | SF {sf.score_drops_200cp}",
        f"- **Extreme numeric evaluations excluded from score-change proxy**: Youloss {tm.excluded_eval_outliers} | SF {sf.excluded_eval_outliers} (absolute value > 1000 cp)",
        "- These proxy counts are descriptive only; they do not identify a blunder or recommend a tuning change.",
        f"- **Max Move Duration**: Youloss {tm.max_move_time_s:.3f}s | SF {sf.max_move_time_s:.3f}s",
        "- **Guidance**:",
        *[f"  - {r}" for r in recs],
        "",
    ]


def build_markdown_report(
    partitions: dict[RunPartitionKey, dict],
    excluded_runs: list[ExcludedRun],
) -> str:
    now_str = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    lines = [
        "# Continuous Screening Telemetry & Partitioned Insights",
        "",
        f"**Generated:** {now_str}",
        f"**Valid Partitions:** {len(partitions)} | **Excluded/Failed Runs:** {len(excluded_runs)}",
        "",
        "## 1. Valid Configuration Partitions",
        "",
    ]

    if not partitions:
        lines.append("_No valid completed runs available for strength summary._\n")

    for key in sorted(
        partitions.keys(),
        key=lambda k: (
            k.tc,
            k.engine_sha256,
            k.sf_engine_sha256,
            k.runner_sha256,
            k.threads,
        ),
    ):
        p = partitions[key]
        lines.extend(
            generate_partition_markdown(
                key,
                p["results"],
                p["paired_results"],
                p["tm_telemetry"],
                p["sf_telemetry"],
                p["recommendations"],
                p["source_runs"],
            )
        )

    lines.append("## 2. Excluded, Failed, or Malformed Runs")
    lines.append("")
    if not excluded_runs:
        lines.append("None (all inspected runs passed validation).\n")
    else:
        lines.append("| Run Directory | Exclusion Reason |")
        lines.append("| :--- | :--- |")
        for exc in sorted(excluded_runs, key=lambda x: x.rundir):
            lines.append(f"| `{Path(exc.rundir).name}` | {exc.reason} |")
        lines.append("")

    return "\n".join(lines)


def serialize_telemetry(t: EngineTelemetry) -> dict:
    return {
        "opening": asdict(t.opening),
        "early_mid": asdict(t.early_mid),
        "late_mid": asdict(t.late_mid),
        "endgame": asdict(t.endgame),
        "score_drops_100cp": t.score_drops_100cp,
        "score_drops_200cp": t.score_drops_200cp,
        "excluded_eval_outliers": t.excluded_eval_outliers,
        "max_move_time_s": t.max_move_time_s,
    }


def analyze_screening_runs(
    run_dirs: list[Path],
) -> tuple[dict[RunPartitionKey, dict], list[ExcludedRun]]:
    """Analyze all run directories, validating, reconciling counts, and partitioning."""
    partitions: dict[RunPartitionKey, dict] = {}
    excluded: list[ExcludedRun] = []

    for rundir in sorted(run_dirs):
        key, failure_reason, meta = validate_run_directory(rundir)
        if failure_reason is not None or key is None:
            excluded.append(
                ExcludedRun(
                    rundir=str(rundir), reason=failure_reason or "Unknown failure"
                )
            )
            continue

        pgn_path = rundir / "match.pgn"
        try:
            results, tm_stats, sf_stats, pgn_games = parse_pgn_file(pgn_path)
            paired_scores, unpaired_games = parse_paired_scores(pgn_path)
        except (OSError, ValueError) as e:
            excluded.append(
                ExcludedRun(rundir=str(rundir), reason=f"PGN parse error: {e}")
            )
            continue

        expected = meta.get("expected_games")
        completed = meta.get("completed_games")
        is_sprt = bool(meta.get("sprt"))

        if pgn_games != completed:
            excluded.append(
                ExcludedRun(
                    rundir=str(rundir),
                    reason=f"Game count mismatch: PGN has {pgn_games}, meta.completed_games is {completed}",
                )
            )
            continue

        if not is_sprt and pgn_games != expected:
            excluded.append(
                ExcludedRun(
                    rundir=str(rundir),
                    reason=f"Incomplete fixed run: PGN has {pgn_games}, meta.expected_games is {expected}",
                )
            )
            continue

        if key not in partitions:
            partitions[key] = {
                "key": key,
                "source_runs": [],
                "results": {"tm_wins": 0, "sf_wins": 0, "draws": 0, "total_games": 0},
                "paired_scores": [],
                "unpaired_games": 0,
                "tm_telemetry": EngineTelemetry(),
                "sf_telemetry": EngineTelemetry(),
            }

        p = partitions[key]
        p["source_runs"].append(str(rundir))
        p["paired_scores"].extend(paired_scores)
        p["unpaired_games"] += unpaired_games
        for k in p["results"]:
            p["results"][k] += results[k]
        accumulate_telemetry(p["tm_telemetry"], tm_stats)
        accumulate_telemetry(p["sf_telemetry"], sf_stats)

    for p in partitions.values():
        p["paired_results"] = summarize_paired_scores(
            p["paired_scores"], p["unpaired_games"]
        )
        p["recommendations"] = generate_recommendations(
            p["tm_telemetry"], p["sf_telemetry"], p["results"]
        )

    return partitions, excluded


def load_scoreboard_run_dirs(scoreboard_path: Path) -> list[Path]:
    """Extract and validate completed run directories from a session scoreboard.

    Returns the exact list of completed run directories listed in the scoreboard.
    Fails clearly if the scoreboard is missing/invalid or if any listed run is missing or invalid.
    """
    if not scoreboard_path.exists():
        raise FileNotFoundError(f"Scoreboard file '{scoreboard_path}' does not exist")
    if not scoreboard_path.is_file():
        raise ValueError(f"Scoreboard path '{scoreboard_path}' is not a file")

    try:
        data = json.loads(scoreboard_path.read_text(encoding="utf-8"))
    except Exception as e:
        raise ValueError(
            f"Malformed scoreboard JSON in '{scoreboard_path}': {e}"
        ) from e

    if not isinstance(data, dict):
        raise TypeError(f"Scoreboard '{scoreboard_path}' must contain a JSON object")

    raw_batches = data.get("recent_batches")
    if raw_batches is None:
        raw_batches = data.get("completed_runs", data.get("runs"))

    if raw_batches is None or not isinstance(raw_batches, list):
        raise TypeError(
            f"Scoreboard '{scoreboard_path}' is missing a valid batch list ('recent_batches')"
        )

    if not raw_batches:
        raise ValueError(f"Scoreboard '{scoreboard_path}' contains zero completed runs")

    run_dirs: list[Path] = []
    for idx, item in enumerate(raw_batches):
        if isinstance(item, dict):
            rundir_val = item.get("rundir")
            if not rundir_val or not isinstance(rundir_val, str):
                raise ValueError(
                    f"Scoreboard entry #{idx} in '{scoreboard_path}' is missing a valid 'rundir'"
                )
        elif isinstance(item, str):
            rundir_val = item
        else:
            raise TypeError(
                f"Scoreboard entry #{idx} in '{scoreboard_path}' has invalid format"
            )

        p = Path(rundir_val)
        if (
            not p.is_absolute()
            and not p.exists()
            and (scoreboard_path.parent / p).exists()
        ):
            p = scoreboard_path.parent / p

        if not p.exists():
            raise FileNotFoundError(
                f"Run directory listed in scoreboard does not exist: '{p}'"
            )
        if not p.is_dir():
            raise ValueError(f"Run path listed in scoreboard is not a directory: '{p}'")
        if not (p / "meta.json").is_file():
            raise FileNotFoundError(
                f"Run directory listed in scoreboard is missing meta.json: '{p}'"
            )
        run_dirs.append(p)

    return run_dirs


def find_candidate_run_dirs(search_path: Path) -> list[Path]:
    """Find run directories under path (either the path itself or immediate child dirs)."""
    if not search_path.is_dir():
        return []
    if (search_path / "meta.json").is_file():
        return [search_path]
    return [
        d for d in search_path.iterdir() if d.is_dir() and (d / "meta.json").is_file()
    ]


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Analyze continuous screening PGN logs"
    )
    parser.add_argument(
        "--sprt-dir",
        type=Path,
        default=None,
        help="Path to sprt run directory or parent directory containing runs",
    )
    parser.add_argument(
        "--scoreboard",
        type=Path,
        default=None,
        help="Path to session scoreboard.json whose completed run directories should be analyzed",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=None,
        help="Path to output directory (default: logs/screening or scoreboard parent directory)",
    )
    args = parser.parse_args()

    if args.scoreboard is not None and args.sprt_dir is not None:
        print("Error: Cannot specify both --scoreboard and --sprt-dir", file=sys.stderr)
        return 1

    if args.scoreboard is not None:
        try:
            candidate_dirs = load_scoreboard_run_dirs(args.scoreboard)
        except (FileNotFoundError, ValueError, TypeError) as e:
            print(f"Error: {e}", file=sys.stderr)
            return 1
        output_dir = (
            args.output_dir if args.output_dir is not None else args.scoreboard.parent
        )
    else:
        sprt_dir = args.sprt_dir if args.sprt_dir is not None else Path("logs/sprt")
        if not sprt_dir.exists():
            print(f"Error: sprt-dir '{sprt_dir}' does not exist", file=sys.stderr)
            return 1

        candidate_dirs = find_candidate_run_dirs(sprt_dir)
        if not candidate_dirs:
            print(
                f"Error: No run directories with meta.json found under '{sprt_dir}'",
                file=sys.stderr,
            )
            return 1
        output_dir = (
            args.output_dir if args.output_dir is not None else Path("logs/screening")
        )

    partitions, excluded = analyze_screening_runs(candidate_dirs)

    output_dir.mkdir(parents=True, exist_ok=True)

    md_report = build_markdown_report(partitions, excluded)
    out_md = output_dir / "tuning_insights.md"
    out_md.write_text(md_report, encoding="utf-8")

    json_partitions = []
    for key in sorted(
        partitions.keys(),
        key=lambda k: (
            k.tc,
            k.engine_sha256,
            k.sf_engine_sha256,
            k.runner_sha256,
            k.threads,
        ),
    ):
        p = partitions[key]
        json_partitions.append(
            {
                "config": asdict(key),
                "source_runs": sorted(p["source_runs"]),
                "results": p["results"],
                "paired_results": p["paired_results"],
                "tm_telemetry": serialize_telemetry(p["tm_telemetry"]),
                "sf_telemetry": serialize_telemetry(p["sf_telemetry"]),
                "recommendations": p["recommendations"],
            }
        )

    out_json = output_dir / "diagnostics.json"
    diag_data = {
        "analyzed_at": datetime.now(timezone.utc).isoformat(),
        "total_runs_inspected": len(candidate_dirs),
        "valid_partitions_count": len(partitions),
        "excluded_runs_count": len(excluded),
        "partitions": json_partitions,
        "excluded_runs": [asdict(e) for e in sorted(excluded, key=lambda x: x.rundir)],
    }
    out_json.write_text(json.dumps(diag_data, indent=2), encoding="utf-8")

    print(
        f"Analyzed {len(candidate_dirs)} runs ({len(partitions)} valid partition(s), {len(excluded)} excluded). "
        f"Outputs written to {out_md} and {out_json}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
